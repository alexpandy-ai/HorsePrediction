type Trio = [number, number, number];

function split([runs, wins, places]: Trio): RecordSplit {
  return { runs, wins, places };
}

function horse(
  raceId: string,
  no: number,
  name: string,
  draw: number,
  kg: number,
  age: number,
  sex: Sex,
  trainer: string,
  jockey: string,
  claim: number,
  officialRating: number | null,
  form: string,
  days: number | null,
  gear: string,
  nonRunner: boolean,
  pace: PaceStyle,
  lastClass: string | null,
  lastLevel: number | null,
  lastKg: number | null,
  lastOr: number | null,
  distance: Trio,
  course: Trio,
  going: Trio,
  speeds: number[],
  publishedSpeed: number | null,
): Runner {
  return {
    id: `${raceId}-${no}`,
    raceId,
    number: no,
    name,
    draw,
    handicapKg: kg,
    age,
    sex,
    trainer,
    jockey,
    claimKg: claim,
    officialRating,
    form,
    daysSince: days,
    equipment: gear,
    nonRunner,
    paceStyle: pace,
    lastClassLabel: lastClass,
    lastClassLevel: lastLevel,
    lastWeightKg: lastKg,
    lastOfficialRating: lastOr,
    distanceRecord: split(distance),
    courseRecord: split(course),
    goingRecord: split(going),
    recentSpeed: speeds,
    publishedSpeed,
  };
}

